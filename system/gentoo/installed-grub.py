#!/usr/bin/env python3
"""Generate the installed encrypted-root GRUB menu; never install GRUB or firmware."""
# SPDX-License-Identifier: GPL-3.0-or-later
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

BOOT_MARKER = 'ms1504.boot=encrypted-root'
UUID = r'[0-9a-fA-F]{8}(?:-[0-9a-fA-F]{4}){3}-[0-9a-fA-F]{12}'


def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def mapping(path):
    result = {}
    for line in path.read_text().splitlines():
        key, value = line.split('=', 1)
        require(key not in result, 'duplicate identity field: ' + key)
        result[key] = value
    return result


def plan(root, release, root_uuid=None):
    root = root.resolve(strict=True)
    require(re.fullmatch(r'[0-9][A-Za-z0-9._+-]*', release), 'invalid kernel release')
    identity = mapping(root / 'etc/ms1504-root-identity')
    require(identity.get('profile') in ('hardware', 'vm'), 'installed root identity missing')
    vg = identity.get('volume_group', '')
    require(re.fullmatch(r'[A-Za-z_][A-Za-z0-9_-]{0,30}', vg), 'invalid installed VG')
    roots = [line.split()[0][5:] for line in (root / 'etc/fstab').read_text().splitlines()
             if line.strip() and not line.lstrip().startswith('#') and
             len(line.split()) >= 2 and line.split()[1] == '/' and line.split()[0].startswith('UUID=')]
    require(len(roots) == 1 and re.fullmatch(UUID, roots[0]), 'expected one root filesystem UUID in fstab')
    require(root_uuid is None or root_uuid.lower() == roots[0].lower(), 'root UUID differs from fstab')
    root_uuid = roots[0]
    cmdline = (root / 'etc/kernel/cmdline').read_text().strip()
    require(re.fullmatch(r'[A-Za-z0-9_=/.+, :\-]+', cmdline), 'unsafe installed kernel command line')
    tokens = cmdline.split()
    require(not any(t.startswith(('init=', 'BOOT_IMAGE=')) for t in tokens), 'bootstrap init/boot arguments in installed command line')
    for prefix in ('root=', 'rd.luks.uuid=', 'resume=', 'ms1504.generation='):
        require(sum(t.startswith(prefix) for t in tokens) == 1, 'missing/duplicate argument: ' + prefix)
    require(f'root=/dev/mapper/{vg}-{identity.get("root_lv", "root")}' in tokens, 'wrong installed root mapper')
    require(f'resume=/dev/mapper/{vg}-{identity.get("swap_lv", "swap")}' in tokens, 'wrong swap mapper')
    require(any(re.fullmatch('rd.luks.uuid=luks-' + UUID, t) for t in tokens), 'invalid LUKS UUID argument')
    for name in ('root', 'home', 'swap'):
        require(f'rd.lvm.lv={vg}/{identity.get(name + "_lv", name)}' in tokens, 'missing LVM activation: ' + name)
    markers = [t for t in tokens if t.startswith('ms1504.boot=')]
    require(not markers or markers == [BOOT_MARKER], 'unexpected boot route marker')
    if not markers:
        tokens.append(BOOT_MARKER)
    kernel = root / 'boot' / ('vmlinuz-' + release)
    initramfs = root / 'boot' / ('initramfs-' + release + '.img')
    for path in (kernel, initramfs):
        require(path.is_file() and path.stat().st_size and path.resolve().is_relative_to(root), 'missing/unsafe boot artifact: ' + str(path))
        require(path.stat().st_dev == root.stat().st_dev, '/boot must be on the encrypted root filesystem')
    text = f'''# Generated by installed-grub.py. Read after firmware unlocks the installed LUKS/LVM root.
# No bootstrap init=/bin/bash; load the matching dracut initramfs.
set timeout=5
set default='gentoo-installed'
menuentry 'Gentoo {release} (encrypted root)' --id gentoo-installed {{
    insmod lvm
    insmod ext2
    insmod search_fs_uuid
    search --no-floppy --fs-uuid --set=root {root_uuid}
    linux /boot/vmlinuz-{release} {' '.join(tokens)}
    initrd /boot/initramfs-{release}.img
}}
'''
    record = {'version': 1, 'release': release, 'root_uuid': root_uuid,
              'kernel_sha256': sha(kernel), 'initramfs_sha256': sha(initramfs),
              'cmdline': tokens, 'grub_sha256': hashlib.sha256(text.encode()).hexdigest()}
    return text, record


def atomic(path, data, mode):
    require(not path.is_symlink(), 'refusing a symlink destination: ' + str(path))
    fd, name = tempfile.mkstemp(prefix='.' + path.name + '.', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(name, mode)
        os.replace(name, path)
        directory = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def publish(root, release, root_uuid=None, check_in_chroot=False):
    root = root.resolve(strict=True)
    text, record = plan(root, release, root_uuid)
    require(not (root / 'etc/ms1504-signed-generation.toml').exists(),
            'signed-generation configuration exists; do not replace its menu with an unsigned base menu')
    menu = root / 'boot/grub/grub.cfg'
    state = root / 'var/lib/ms1504-gentoo/boot'
    for path in (menu.parent, state):
        require(not path.is_symlink() and path.resolve().is_relative_to(root), 'unsafe boot directory')
        path.mkdir(parents=True, exist_ok=True)
    os.chmod(state, 0o700)
    # Validate before replacing even a previously generated/broken menu.
    with tempfile.NamedTemporaryFile(mode='w', dir=menu.parent, prefix='.check-', delete=False) as stream:
        temporary = Path(stream.name)
        stream.write(text)
    try:
        if check_in_chroot:
            require(root != Path('/'), 'chroot checker requires an offline target root')
            subprocess.run(['chroot', str(root), '/usr/bin/env', '-i',
                            'PATH=/usr/bin:/usr/sbin:/bin:/sbin', 'grub-script-check',
                            '/' + str(temporary.relative_to(root))], check=True)
        else:
            subprocess.run(['grub-script-check', str(temporary)], check=True)
    finally:
        temporary.unlink()
    if menu.exists():
        require(menu.is_file() and not menu.is_symlink(), 'existing GRUB menu is unsafe')
        previous = menu.read_bytes()
        if previous != text.encode():
            backup = state / ('grub.cfg.before-' + hashlib.sha256(previous).hexdigest())
            if backup.exists():
                require(backup.is_file() and not backup.is_symlink() and backup.read_bytes() == previous, 'backup differs')
            else:
                atomic(backup, previous, 0o600)
    atomic(menu, text.encode(), 0o644)
    atomic(state / 'encrypted-root-grub.json', (json.dumps(record, sort_keys=True, indent=2) + '\n').encode(), 0o600)
    return record


def check_running(root=Path('/')):
    require(root.resolve() == Path('/'), 'running-boot check must target /')
    state = root / 'var/lib/ms1504-gentoo/boot/encrypted-root-grub.json'
    require(state.is_file() and not state.is_symlink() and state.stat().st_uid == 0 and
            state.stat().st_mode & 0o077 == 0, 'protected encrypted-root boot record missing')
    saved = json.loads(state.read_text())
    text, record = plan(root, saved['release'])
    require(saved == record and (root / 'boot/grub/grub.cfg').read_text() == text, 'encrypted-root boot files/configuration changed')
    running = Path('/proc/cmdline').read_text().split()
    source = subprocess.check_output(['findmnt', '-rn', '-M', '/', '-o', 'SOURCE'], text=True).strip()
    actual = subprocess.check_output(['blkid', '-s', 'UUID', '-o', 'value', source], text=True).strip()
    verify_boot_arguments(record, running, os.uname().release, actual)
    return record


def verify_boot_arguments(record, running, release, root_uuid):
    require(BOOT_MARKER in running and all(token in running for token in record['cmdline']),
            'reboot through the generated encrypted-root GRUB entry before erasing extra')
    require(release == record['release'], 'running kernel release differs from encrypted-root entry')
    require(root_uuid.lower() == record['root_uuid'].lower(), 'running root filesystem UUID differs')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path('/'))
    parser.add_argument('--release', default='6.12.111')
    parser.add_argument('--root-uuid')
    parser.add_argument('--check-in-chroot', action='store_true', help='run the source-built GRUB checker inside the offline target root')
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--apply', action='store_true')
    mode.add_argument('--check-running', action='store_true')
    args = parser.parse_args()
    if args.check_running:
        check_running(args.root)
        print('Running encrypted-root boot entry and local kernel/initramfs verified.')
    elif args.apply:
        require(os.geteuid() == 0, 'run as root to publish the menu')
        record = publish(args.root, args.release, args.root_uuid, args.check_in_chroot)
        print('Generated encrypted /boot/grub/grub.cfg; root UUID=' + record['root_uuid'])
        print('Existing menu backed up if changed. No GRUB installation or firmware write performed.')
    else:
        print(plan(args.root, args.release, args.root_uuid)[0], end='')


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, KeyError, subprocess.CalledProcessError) as error:
        raise SystemExit('installed-grub: ' + str(error))
